-- Fase 2: value semantics, inventory persistence and dependency ordering.
package.path='./lua-engine/?.lua;./lua-engine/?/init.lua;'..package.path
local Stack=require('core.itemstack')
local Inventory=require('core.inventory')
local Loader=require('core.modloader')
local Engine=require('core.runtime')
local Storage=require('core.storage')
local function eq(a,b,label)
 assert(a==b,(label or 'value')..': '..tostring(a)..' != '..tostring(b))
end
local e=Engine.new()
local api=e.api
api.register_node('test:stone',{stack_max=99,groups={cracky=2}})
api.register_tool('test:tool',{stack_max=1})
api.register_craftitem('test:apple',{stack_max=10})
local a=api.ItemStack('test:stone 40 2')
eq(a:get_name(),'test:stone')
eq(a:get_count(),40)
eq(a:get_wear(),2)
eq(tostring(a),'test:stone 40 2')
local b=api.ItemStack(a)
assert(a:equals(b))
b:set_count(30)
eq(a:get_count(),40,'ItemStack copy')
eq(b:get_count(),30)
eq(a:get_free_space(),59)
local taken=a:take_item(10)
eq(taken:get_count(),10)
eq(a:get_count(),30)
local remainder=a:add_item('test:stone 90 2')
eq(a:get_count(),99,'max stacking')
eq(remainder:get_count(),21,'leftover')
eq(a:get_free_space(),0)
eq(a:peek_item(4):get_count(),4)
eq(a:get_count(),99,'peek does not mutate')
assert(a:add_item('test:tool 1'):get_count()==1)
local meta=a:get_meta()
meta:set_string('owner','Lua😀')
eq(meta:get_string('owner'),'Lua😀')
assert(not a:stackable(api.ItemStack('test:stone 5 2')),
 'metadata matters to stack identity')
local tagged=api.ItemStack(a)
assert(a:stackable(tagged))
eq(tagged:get_meta():get_string('owner'),'Lua😀')
tagged:get_meta():set_string('owner','Other')
eq(a:get_meta():get_string('owner'),'Lua😀','deep copied metadata')
local empty=Stack.new()
eq(tostring(empty),'')
assert(empty:is_empty())
empty:set_name('test:apple')
eq(empty:get_count(),1)
empty:set_count(0)
assert(empty:is_empty())
local tool=api.ItemStack('test:tool')
eq(tool:get_stack_max(),1)
eq(tool:add_item('test:tool 3'):get_count(),3,'full tool')
local iv=api.create_detached_inventory('testing')
iv:set_size('main',3)
iv:set_width('main',3)
eq(iv:get_size('main'),3)
eq(iv:get_width('main'),3)
assert(iv:set_stack('main',1,'test:stone 90'))
assert(iv:set_stack('main',2,'test:tool'))
local hand=iv:get_stack('main',1)
hand:set_count(1)
eq(iv:get_stack('main',1):get_count(),90,'inventory getter returns copy')
assert(iv:room_for_item('main','test:stone 20'))
local leftover=iv:add_item('main','test:stone 20')
assert(leftover:is_empty())
eq(iv:get_stack('main',1):get_count(),99)
eq(iv:get_stack('main',3):get_count(),11)
assert(iv:contains_item('main','test:stone 110'))
assert(not iv:contains_item('main','test:stone 111'))
local removed=iv:remove_item('main','test:stone 105')
eq(removed:get_count(),105)
eq(iv:get_stack('main',1):get_count(),0)
eq(iv:get_stack('main',3):get_count(),5)
eq(iv:remove_item('main','test:tool 3'):get_count(),1)
assert(iv:is_empty('missing'))
local copied=iv:get_list('main')
copied[3]:clear()
eq(iv:get_stack('main',3):get_count(),5)
local v=iv:to_table()
local other=Inventory.new(api.registered_items)
other:from_table(v)
eq(other:get_stack('main',3):get_count(),5)
eq(other:get_width('main'),3)
eq(api.get_inventory({type='detached',name='testing'}),iv)
eq(api.get_inventory({type='detached',name='not-here'}),nil)
local loc={type='node',pos={x=-1,y=2,z=4}}
local bin=api.get_inventory(loc)
bin:set_size('main',2)
bin:set_width('main',2)
local stack=api.ItemStack('test:stone 11 10')
stack:get_meta():set_string('label','pessoa & lua')
bin:set_stack('main',1,stack)
bin:set_stack('main',2,'test:tool')
api.get_meta(loc.pos):set_string('owner','Main')
local saved=Storage.encode(e.map)
assert(saved:find('L %-1 2 4'))
assert(saved:find('F %-1 2 4'))
local map=Storage.decode(saved)
local restored=map:get_meta(loc.pos):get_inventory()
eq(restored:get_size('main'),2)
eq(restored:get_width('main'),2)
eq(restored:get_stack('main',1):get_wear(),10)
eq(restored:get_stack('main',1):get_count(),11)
eq(restored:get_stack('main',1):get_meta():get_string('label'),'pessoa & lua')
eq(restored:get_stack('main',2):get_name(),'test:tool')
eq(map:get_meta(loc.pos):get_string('owner'),'Main')
assert(not pcall(Storage.decode,'LUAENGINE 1\nI 0 0 0 main 1 stone 1 0\nEND\n'))
-- Copy of node metadata does not mutate stored inventory state.
local mt=api.get_meta(loc.pos):to_table()
eq(mt.inventory.main.size,2)
local target={x=3,y=3,z=3}
api.get_meta(target):from_table(mt)
eq(api.get_meta(target):get_inventory():get_stack('main',1):get_name(),'test:stone')
api.get_meta(target):get_inventory():set_stack('main',1,nil)
eq(api.get_meta(loc.pos):get_inventory():get_stack('main',1):get_count(),11)
local parsed=Loader.parse([[
name = mcl_core
description = Blocks
depends = mcl_init, mcl_util
optional_depends = doc, vl_tuning
]])
eq(parsed.name,'mcl_core')
eq(parsed.depends[1],'mcl_init')
eq(parsed.depends[2],'mcl_util')
eq(parsed.optional_depends[1],'doc')
local legacy=Loader.parse('name = older\n','mcl_init\ndoc?\n')
eq(legacy.depends[1],'mcl_init')
eq(legacy.optional_depends[1],'doc')
local mods={
 {name='mcl_core',path='game/mods/core',depends={'mcl_init','mcl_util'},
  optional_depends={'missing_optional','vl_tuning'}},
 {name='mcl_util',path='game/mods/util',depends={'mcl_init'}},
 {name='vl_tuning',path='game/mods/tuning'},
 {name='mcl_init',path='game/mods/init'}
}
local plan=Loader.plan(mods)
local order={}
for _,m in ipairs(plan) do order[#order+1]=m.name end
eq(table.concat(order,','),'mcl_init,mcl_util,vl_tuning,mcl_core')
-- Note: independent mods are sorted alphabetically before DFS.
assert(not pcall(Loader.plan,{{name='a',path='a',depends={'b'}}}))
assert(not pcall(Loader.plan,{{name='a',path='a',depends={'b'}},
 {name='b',path='b',depends={'a'}}}))
assert(not pcall(Loader.plan,{{name='same',path='a'},{name='same',path='b'}}))
local fakeFiles={
 ['mods/mcl_init/mod.conf']='name = mcl_init\n',
 ['mods/mcl_util/mod.conf']='name = mcl_util\ndepends = mcl_init\n',
 ['mods/mcl_core/mod.conf']='name = mcl_core\ndepends = mcl_util\n'
}
local found=Loader.discover('mods',{
 walk=function() return {'mods/mcl_core','mods/mcl_util','mods/mcl_init'} end,
 read=function(path) return fakeFiles[path] end
})
eq(found[1].name,'mcl_init')
eq(found[3].name,'mcl_core')
local loaded,events={},{};
local rt=Engine.new({executeMod=function(path,name)
 loaded[#loaded+1]=name
 eq(api.get_current_modname(),nil,'unrelated runtime unaffected')
end})
rt:installGlobals({})
rt.api.register_on_mods_loaded(function() events[#events+1]='ready' end)
local ok,results=Loader.load(rt,found)
assert(ok)
eq(#results,3)
eq(table.concat(loaded,','),'mcl_init,mcl_util,mcl_core')
eq(#events,1)
eq(rt.api.get_current_modname(),nil)
eq(rt.api.get_modpath('mcl_util'),'mods/mcl_util')
local fail=Engine.new({executeMod=function(path,name)
 if name=='mcl_util' then error('failed') end
end})
local success,report=Loader.load(fail,found)
assert(not success)
eq(#report,2)
assert(report[2].error:find('mcl_util'))
eq(fail.api.get_current_modname(),nil)
local ok2,all=Loader.load(fail,found,{continue_on_error=true})
assert(not ok2)
eq(#all,3)
print('lua_engine_inventory_modloader: OK')
